import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { join, posix } from 'node:path';
import { PLANS_DIRS } from './locate.ts';
import { DOCS_DIR } from './paths.ts';
import { stripControl } from './util.ts';

export const USAGE_REL = `${DOCS_DIR}/USAGE.md`;
const USAGE_MARK = "<!-- Generated by cairn from each plan's usage.json. Edits here are overwritten. -->";

export interface StageUsage {
  usd: number;
  tokens: number;
  weekPct: number;
}

export interface PlanUsage {
  usd: number;
  tokens: { input: number; output: number; cacheRead: number; cacheWrite: number; total: number };
  tokensByModel: Record<string, number>;
  weekPct: number;
  byStage: Record<string, StageUsage>;
  sessions: number;
}

const num = (v: unknown): number => (typeof v === 'number' && Number.isFinite(v) ? v : 0);
const isObj = (v: unknown): v is Record<string, unknown> => typeof v === 'object' && v !== null && !Array.isArray(v);

/** Totals over every session file the mod wrote for this plan; undefined when there is none. Unreadable files are skipped. */
export function planUsage(commonDir: string, slug: string): PlanUsage | undefined {
  const dir = join(commonDir, 'cairn', 'usage', slug);
  let names: string[];
  try {
    names = readdirSync(dir).filter((n) => n.endsWith('.json'));
  } catch {
    return undefined;
  }
  const t: PlanUsage = { usd: 0, tokens: { input: 0, output: 0, cacheRead: 0, cacheWrite: 0, total: 0 }, tokensByModel: {}, weekPct: 0, byStage: {}, sessions: 0 };
  for (const n of names) {
    let j: unknown;
    try {
      j = JSON.parse(readFileSync(join(dir, n), 'utf8'));
    } catch {
      continue;
    }
    if (!isObj(j)) continue;
    t.sessions++;
    t.usd += num(j.usd);
    t.weekPct += num(j.weekPct);
    const tk = isObj(j.tokens) ? j.tokens : {};
    for (const k of ['input', 'output', 'cacheRead', 'cacheWrite'] as const) t.tokens[k] += num(tk[k]);
    if (isObj(j.tokensByModel)) for (const [m, v] of Object.entries(j.tokensByModel)) t.tokensByModel[m] = (t.tokensByModel[m] ?? 0) + num(v);
    if (isObj(j.byStage))
      for (const [st, v] of Object.entries(j.byStage)) {
        if (!isObj(v)) continue;
        const b = (t.byStage[st] ??= { usd: 0, tokens: 0, weekPct: 0 });
        b.usd += num(v.usd);
        b.tokens += num(v.tokens);
        b.weekPct += num(v.weekPct);
      }
  }
  if (!t.sessions) return undefined;
  t.tokens.total = t.tokens.input + t.tokens.output + t.tokens.cacheRead + t.tokens.cacheWrite;
  return t;
}

const round1 = (n: number) => Math.round(n * 10) / 10;

/** 850, 45k, 1.2M. */
export function formatTokens(n: number): string {
  if (n < 1000) return String(Math.round(n));
  if (n < 1e6) return `${n < 1e4 ? round1(n / 1e3) : Math.round(n / 1e3)}k`;
  return `${n < 1e7 ? round1(n / 1e6) : Math.round(n / 1e6)}M`;
}

const usd = (n: number) => `$${n.toFixed(2)}`;
export const formatWeekPct = (p: number): string => (p < 10 ? String(round1(p)) : String(Math.round(p)));

/** `$42.10 · 18.2M tokens · ≈18% of weekly limit`. The weekly part is left out when it is zero. */
export function formatUsage(u: { usd: number; weekPct: number; tokens: { total: number } }): string {
  return [usd(u.usd), `${formatTokens(u.tokens.total)} tokens`, ...(u.weekPct > 0 ? [`≈${formatWeekPct(u.weekPct)}% of weekly limit`] : [])].join(' · ');
}

/** The 2-3 costliest stages: `execute $10 · review $2.50`. */
export function topStages(byStage: Record<string, StageUsage>, n = 3): string {
  return Object.entries(byStage)
    .filter(([, v]) => v.usd > 0)
    .sort((a, b) => b[1].usd - a[1].usd)
    .slice(0, n)
    .map(([k, v]) => `${stripControl(k)} $${Number.isInteger(v.usd) ? v.usd : v.usd.toFixed(2)}`)
    .join(' · ');
}

interface Row {
  rel: string;
  closedAt: string;
  slug: string;
  usage: Record<string, unknown>;
}

/** The generated usage table from every plan folder's usage.json under `root`, newest closed first. */
export function renderUsage(root: string): string {
  const rows: Row[] = [];
  for (const d of PLANS_DIRS) {
    let names: string[] = [];
    try {
      names = readdirSync(join(root, d));
    } catch {
      continue;
    }
    for (const n of names) {
      try {
        const j: unknown = JSON.parse(readFileSync(join(root, d, n, 'usage.json'), 'utf8'));
        if (!isObj(j) || !isObj(j.tokens)) continue;
        rows.push({ rel: `${d}/${n}`, closedAt: typeof j.closedAt === 'string' ? j.closedAt : '', slug: typeof j.slug === 'string' ? j.slug : n, usage: j });
      } catch {
        // No usage.json, or an unreadable one: the plan is left out.
      }
    }
  }
  rows.sort((a, b) => b.closedAt.localeCompare(a.closedAt) || a.slug.localeCompare(b.slug));
  const out = ['# Usage', '', USAGE_MARK, '', "What each closed plan cost. The weekly share is approximate: it adds up the rises in the account's 7-day limit while the plan was active.", ''];
  if (!rows.length) out.push('None yet.');
  else {
    out.push('| Closed | Plan | Cost | Tokens | ≈ Week % | Top stages |', '| --- | --- | --- | --- | --- | --- |');
    for (const r of rows) {
      const u = r.usage;
      const tk = isObj(u.tokens) ? u.tokens : {};
      const name = stripControl(r.slug);
      const plan = existsSync(join(root, r.rel, 'RECORD.md')) ? `[${name}](${posix.relative(DOCS_DIR, `${r.rel}/RECORD.md`)})` : name;
      const week = num(u.weekPct) > 0 ? `${formatWeekPct(num(u.weekPct))}%` : '';
      const stages = isObj(u.byStage) ? (u.byStage as Record<string, StageUsage>) : {};
      out.push(`| ${r.closedAt.slice(0, 10)} | ${plan} | ${usd(num(u.usd))} | ${formatTokens(num(tk.total))} | ${week} | ${topStages(stages)} |`);
    }
  }
  return `${out.join('\n')}\n`;
}
