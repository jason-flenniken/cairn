import type { Phase, Slice, Stage, State } from './types.ts';

export const STAGE_LABEL: Record<Stage, string> = {
  repro: 'Repro',
  discover: 'Discover',
  prd: 'PRD',
  plan: 'Plan',
  execute: 'Execute',
  verify: 'Verify',
  review: 'Review',
  ship: 'Ship',
  learn: 'Learn',
  closed: 'Closed',
};

const day = (iso?: string) => (iso ? iso.slice(0, 10) : '');

export interface Next {
  procedure: string;
  substep?: string;
  text: string;
}

const names = (xs: Slice[]) => xs.map((x) => x.name).join(', ');

/** The single correct next step for a plan. */
export function nextFor(s: State): Next {
  if (s.stage === 'closed') return { procedure: 'status', text: 'This plan is closed. Its record is in RECORD.md.' };
  if (s.paused) return { procedure: 'resume', text: `Paused ${day(s.paused.at)}. Resume to pick up where it stopped.` };
  const all = s.phases.flatMap((p) => p.slices);
  switch (s.stage) {
    case 'repro':
      return s.repro
        ? { procedure: 'fix', substep: 'advance', text: 'Repro recorded. Advance to the fix.' }
        : { procedure: 'fix', text: 'Record a command that reproduces the bug (cairn repro).' };
    case 'discover':
      return { procedure: 'discover', text: 'Interview: settle the open decisions, then move on to the PRD.' };
    case 'prd':
      return s.approvals.prd
        ? { procedure: 'prd', substep: 'advance', text: 'PRD approved. Advance to planning.' }
        : { procedure: 'prd', text: 'Draft the PRD, review it, and get it approved.' };
    case 'plan':
      return s.approvals.plan
        ? { procedure: 'plan', substep: 'advance', text: 'Plan approved. Advance to execution.' }
        : { procedure: 'plan', text: 'Write the phased plan, load it, and get it approved.' };
    case 'execute': {
      const phase = s.phases.find((p) => p.status !== 'done');
      if (!phase && s.track === 'fix' && s.repro) return { procedure: 'review', text: 'The fix is built. Advance to review.' };
      if (!phase) return { procedure: 'verify', text: 'All phases are done. Advance to verification.' };
      if (phase.status === 'awaiting_approval')
        return { procedure: 'phase-end', text: `Phase "${phase.name}" is built. Review it and approve it to continue.` };
      const running = all.filter((x) => x.status === 'in_progress');
      if (running.length)
        return { procedure: 'execute', substep: 'continue', text: `Continue running slices: ${running.map((x) => `${x.name} (${x.substep ?? 'implementing'})`).join(', ')}.` };
      return { procedure: 'execute', text: `Start the next ready slices in phase "${phase.name}".` };
    }
    case 'verify':
      return { procedure: 'verify', text: 'Verify the build against the PRD and record the result.' };
    case 'review':
      return { procedure: 'review', text: 'Review the whole branch and record the result.' };
    case 'ship':
      return s.approvals.ship
        ? { procedure: 'ship', substep: 'advance', text: 'Ship approved. Open the PR and advance.' }
        : { procedure: 'ship', text: 'Write the completion record and decide whether to ship.' };
    case 'learn':
      return { procedure: 'learn', text: 'Capture anything worth keeping, then close the plan.' };
  }
}

export function progress(s: State): string {
  const all = s.phases.flatMap((p) => p.slices);
  if (!s.phases.length) return STAGE_LABEL[s.stage];
  const done = all.filter((x) => x.status === 'done').length;
  const running = all.filter((x) => x.status === 'in_progress').length;
  const pi = s.phases.findIndex((p) => p.status !== 'done');
  const phase = pi === -1 ? 'all phases done' : `phase ${pi + 1}/${s.phases.length} "${s.phases[pi].name}"`;
  return `${STAGE_LABEL[s.stage]} · ${phase} · ${done}/${all.length} slices done${running ? ` · ${running} running` : ''}`;
}

const openDrift = (s: State) => s.drift.filter((d) => !d.acked);

export function summary(s: State): string {
  const drift = openDrift(s).length;
  return `${s.title} (${s.slug}): ${progress(s)}${s.paused ? ' · PAUSED' : ''}${drift ? ` · ${drift} unreviewed drift` : ''}`;
}

const sliceIcon = (x: Slice, done: Set<string>) =>
  x.status === 'done' ? '✓' : x.status === 'in_progress' ? '◐' : x.blockedBy.some((b) => !done.has(b)) ? '⊘' : '○';
const phaseIcon = (p: Phase) => ({ done: '✓', awaiting_approval: '◆', in_progress: '◐', pending: '○' })[p.status];

export function renderStatus(s: State): string {
  const next = nextFor(s);
  const all = s.phases.flatMap((p) => p.slices);
  const byId = new Map(all.map((x) => [x.id, x]));
  const done = new Set(all.filter((x) => x.status === 'done').map((x) => x.id));
  const out: string[] = [
    `# ${s.title}: status`,
    '',
    '<!-- Generated by cairn from state.json. Edits here are overwritten. -->',
    '',
    `**Where we are:** ${progress(s)}`,
    `**Next:** ${next.text}`,
  ];
  if (s.paused) out.push(`**Paused** since ${day(s.paused.at)}. See handoff.md.`);
  out.push('', `Branch \`${s.branch}\` from \`${s.base}\` · started ${day(s.created)} · updated ${day(s.updated)}`);

  if (s.phases.length) {
    out.push('', '## Phases');
    for (const p of s.phases) {
      out.push(`- ${phaseIcon(p)} ${p.name}${p.status === 'awaiting_approval' ? ' (built, waiting for approval)' : ''}`);
      for (const x of p.slices) {
        let tail = '';
        if (x.status === 'in_progress') tail = ` (${x.substep ?? 'implementing'}${x.fixRound ? `, fix round ${x.fixRound}` : ''})`;
        else if (x.status === 'pending') {
          const on = x.blockedBy.filter((b) => !done.has(b)).map((b) => byId.get(b)?.name ?? b);
          if (on.length) tail = ` (waits on ${on.join(', ')})`;
        }
        out.push(`  - ${sliceIcon(x, done)} ${x.name}${tail}`);
      }
    }
  }

  const checkpoints: string[] = [];
  const a = s.approvals;
  if (a.prd) checkpoints.push(`PRD approved ${day(a.prd.at)}${a.prd.via === 'agent' ? ' (relayed by agent)' : ''}`);
  if (a.plan) checkpoints.push(`Plan approved ${day(a.plan.at)}${a.plan.via === 'agent' ? ' (relayed by agent)' : ''}`);
  if (s.evidence.verify) checkpoints.push(`Verify: ${s.evidence.verify.result}${s.evidence.verify.note ? ` (${s.evidence.verify.note})` : ''}`);
  if (s.evidence.review) checkpoints.push(`Review: ${s.evidence.review.result}${s.evidence.review.note ? ` (${s.evidence.review.note})` : ''}`);
  if (a.ship) checkpoints.push(`Ship approved ${day(a.ship.at)}`);
  if (checkpoints.length) out.push('', '## Checkpoints', ...checkpoints.map((c) => `- ${c}`));

  const drift = openDrift(s);
  if (drift.length) out.push('', '## Drift to review', ...drift.map((d) => `- \`${d.path}\`: ${d.reason}`));

  const overrides = s.log.filter((l) => l.override);
  if (overrides.length) out.push('', '## Overrides', ...overrides.map((l) => `- ${day(l.at)} ${l.event}: ${l.override}`));

  out.push('', '## Recent activity', ...s.log.slice(-8).reverse().map((l) => `- ${l.at.slice(0, 16).replace('T', ' ')} ${l.event}${l.detail ? `: ${l.detail}` : ''}`));
  return out.join('\n') + '\n';
}

export interface IndexRow {
  state: State;
  live: boolean;
  worktree?: string;
}

export function renderIndex(rows: IndexRow[]): string {
  const out = ['# Plans', '', '<!-- Generated by cairn. Edits here are overwritten. -->', ''];
  if (!rows.length) return out.concat('No plans yet. Start one with `/cairn:new`.').join('\n') + '\n';
  out.push('| Plan | Where | Next | Worktree |', '|---|---|---|---|');
  for (const r of rows)
    out.push(`| ${r.state.title} (\`${r.state.slug}\`) | ${progress(r.state)}${r.state.paused ? ' · PAUSED' : ''} | ${nextFor(r.state).text} | ${r.worktree ?? '(not checked out)'} |`);
  return out.join('\n') + '\n';
}
