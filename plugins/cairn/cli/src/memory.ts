import { existsSync } from 'node:fs';
import { basename, join, posix } from 'node:path';
import { changelogText, type PlanEntry } from './commands/records.ts';
import { PLANS_DIRS } from './locate.ts';
import { DOCS_DIR } from './paths.ts';
import { stripControl } from './util.ts';

export const OVERVIEW_REL = `${DOCS_DIR}/OVERVIEW.md`;
const CHANGELOG_MARK = '<!-- Generated by cairn from each plan\'s changelog entry and record. Edits here are overwritten. -->';

const NONE = 'None yet.';

/** Repo-relative path of a plan's record as it exists under `root` (new plans root first). Undefined when this checkout does not hold it, so no link points at a missing file. */
const recordRel = (root: string, e: PlanEntry): string | undefined =>
  PLANS_DIRS.map((d) => `${d}/${basename(e.dir)}/RECORD.md`).find((rel) => existsSync(join(root, rel)));
const byNewest = (a: PlanEntry, b: PlanEntry) => b.date.localeCompare(a.date) || a.state.slug.localeCompare(b.state.slug);

/** The generated changelog: one block per closed plan, newest first. Links are relative to the OVERVIEW. */
export function renderChangelog(root: string, plans: PlanEntry[]): string {
  const out = ['# Changelog', '', CHANGELOG_MARK, ''];
  const closed = plans.filter((p) => p.state.stage === 'closed').sort(byNewest);
  if (!closed.length) out.push(NONE);
  for (const p of closed) {
    let text = '';
    try {
      text = changelogText(p, root);
    } catch {
      // An unreadable entry leaves the date and title only.
    }
    const r = recordRel(root, p);
    out.push(`## ${p.date} · ${stripControl(p.state.title)}`, '');
    if (text) out.push(text, '');
    if (r) out.push(`[Record](${posix.relative(DOCS_DIR, r)})`, '');
  }
  return `${out.join('\n').replace(/\n+$/, '')}\n`;
}

const INDEX_ENTRIES = 5;
const INDEX_WORDS = 120;

/** `text` with whitespace collapsed to single spaces, cut to at most `n` words (ellipsis only when cut). */
function cutWords(text: string, n: number): string {
  const words = text.split(/\s+/).filter(Boolean);
  return words.length > n ? `${words.slice(0, n).join(' ')}…` : words.join(' ');
}

/** The short changelog injected at session start: the five newest closed plans, each cut to 120 words, then a pointer line. '' when no plan is closed. A plan whose files cannot be read is skipped. */
export function memoryIndex(root: string, plansOf: PlanEntry[] | (() => PlanEntry[])): string {
  const plans = typeof plansOf === 'function' ? plansOf() : plansOf;
  const lines: string[] = [];
  for (const p of plans.filter((x) => x.state.stage === 'closed').sort(byNewest)) {
    if (lines.length >= INDEX_ENTRIES) break;
    try {
      const text = cutWords(changelogText(p, root), INDEX_WORDS);
      lines.push(`- ${p.date} ${stripControl(p.state.title)}${text ? `: ${text}` : ''}`);
    } catch {
      // Unreadable plan files: leave it out.
    }
  }
  if (!lines.length) return '';
  return ['cairn changelog (newest first):', ...lines, `Older work: ${OVERVIEW_REL}`].join('\n');
}
