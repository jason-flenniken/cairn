import { posix } from 'node:path';
import { areasForScopes, loadAreas, type Area } from './areas.ts';
import { activeDecisionsFor, loadDecisions, type LoggedDecision } from './decision-log.ts';
import { scopesOverlap } from './glob.ts';
import { whyLine, type PlanEntry } from './commands/records.ts';
import { DOCS_DIR } from './paths.ts';
import { allTasks } from './ready.ts';
import { readText } from './util.ts';

export const OVERVIEW_REL = `${DOCS_DIR}/OVERVIEW.md`;
export const HISTORY_MARK = '<!-- Generated by cairn from the decision log and plan records. Edits here are overwritten. -->';

const RECORD_REL = /((?:docs\/cairn|docs\/sdlc)\/plans\/[^/]+\/RECORD\.md)$/;
const NONE = 'None yet.';

/** Repo-relative path of a plan's record, from its absolute path (any worktree). */
const recordRel = (e: PlanEntry): string | undefined => (e.record ? RECORD_REL.exec(e.record.split('\\').join('/'))?.[1] : undefined);
const cell = (s: string) => s.replace(/\s+/g, ' ').replace(/\|/g, '\\|').trim();
const byNewest = (a: PlanEntry, b: PlanEntry) => b.date.localeCompare(a.date) || a.state.slug.localeCompare(b.state.slug);

/** Closed plans that touched an area: its recorded areas, else task scopes that overlap its paths (a `**` scope says nothing). Newest first. */
export function plansTouching(area: Area, plans: PlanEntry[]): PlanEntry[] {
  return plans
    .filter((p) => {
      if (p.state.stage !== 'closed') return false;
      if (p.state.areasTouched) return p.state.areasTouched.includes(area.id);
      const scopes = allTasks(p.state).flatMap((t) => t.scope).filter((g) => g !== '**');
      return scopes.length > 0 && scopesOverlap(scopes, area.paths);
    })
    .sort(byNewest);
}

const decisionsFor = (area: Area, all: LoggedDecision[]): LoggedDecision[] =>
  all.filter((d) => d.areas.includes(area.id) || (d.paths.length > 0 && scopesOverlap(d.paths, area.paths))).sort((a, b) => (a.status === b.status ? a.id.localeCompare(b.id) : a.status === 'active' ? -1 : 1));

/** The lines under an area's History: decisions (in force first), then plans. Links are relative to the area doc. */
export function historyLines(_root: string, area: Area, decisions: LoggedDecision[], plans: PlanEntry[]): string[] {
  const from = posix.dirname(area.file);
  const out = decisionsFor(area, decisions).map((d) => `- Decision [${d.id}](${posix.relative(from, d.file)}): ${cell(d.answer)} (${d.status === 'active' ? 'in force' : `replaced by ${d.replacedBy ?? 'a later decision'}`})`);
  for (const p of plansTouching(area, plans)) {
    const rel = recordRel(p);
    out.push(`- ${p.date} ${rel ? `[${p.state.title}](${posix.relative(from, rel)})` : p.state.title}`);
  }
  return out;
}

/** Replace the body of `## History` with the generated lines; add the section when it is missing. Everything else stays as written. */
export function withHistory(md: string, lines: string[]): string {
  const body = `\n${HISTORY_MARK}\n\n${lines.length ? lines.join('\n') : NONE}\n`;
  const h = /^## History[ \t]*\r?\n/m.exec(md);
  if (!h) return `${md.replace(/\s*$/, '\n')}\n## History\n${body}`;
  const start = h.index + h[0].length;
  const next = /^## /m.exec(md.slice(start));
  return md.slice(0, start) + body + (next ? `\n${md.slice(start + next.index)}` : '');
}

const table = (head: string[], rows: string[][]): string[] => (rows.length ? [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)] : [NONE]);

/** The generated human rollup: areas, decisions in force, replaced decisions, and plans. */
export function renderOverview(_root: string, areas: Area[], decisions: LoggedDecision[], plans: PlanEntry[]): string {
  const rel = (p: string) => posix.relative(DOCS_DIR, p);
  const link = (d: LoggedDecision) => `[${d.id}](${rel(d.file)})`;
  const active = decisions.filter((d) => d.status === 'active').sort((a, b) => a.id.localeCompare(b.id));
  const replaced = decisions.filter((d) => d.status === 'replaced').sort((a, b) => a.id.localeCompare(b.id));
  const out = ['# System overview', '', HISTORY_MARK.replace('the decision log and plan records', 'the area docs, decision log, and plan records'), ''];
  out.push('## Areas', '', ...table(['Area', 'Summary', 'Doc'], areas.map((a) => [cell(a.name), cell(a.summary), `[${a.id}](${rel(a.file)})`])), '');
  out.push('## Decisions in force', '', ...table(['Decision', 'Areas', 'Plan', 'Date'], active.map((d) => [`${link(d)} ${cell(d.answer)}`, d.areas.join(', '), d.plan, d.date])), '');
  out.push('## Replaced decisions', '', ...table(['Decision', 'Replaced by'], replaced.map((d) => [link(d), d.replacedBy ?? ''])), '');
  out.push('## Plans', '');
  const lines = [...plans].sort(byNewest).map((p) => {
    const r = recordRel(p);
    const why = whyLine(p.record ? readText(p.record) : undefined);
    const open = p.state.stage === 'closed' ? '' : ` (in progress: ${p.state.stage})`;
    return `- ${p.date} **${p.state.title}**${open}${why ? `: ${why}` : ''}${r ? ` [record](${rel(r)})` : ''}`;
  });
  out.push(...(lines.length ? lines : [NONE]));
  return `${out.join('\n')}\n`;
}

export interface RecallResult {
  areas: Area[];
  decisions: LoggedDecision[];
  plans: { slug: string; title: string; date: string; record?: string }[];
  /** Globs that no area doc covers. */
  uncovered: string[];
}

const RECALL_PLANS = 5;

/** What the memory holds about these paths: area docs, decisions in force, and the closed plans that touched them. */
export function recall(root: string, globs: string[], plans: PlanEntry[]): RecallResult {
  const areas = areasForScopes(globs, loadAreas(root).areas);
  const decisions = activeDecisionsFor(globs, areas.map((a) => a.id), loadDecisions(root));
  const found = new Map<string, PlanEntry>();
  for (const a of areas) for (const p of plansTouching(a, plans)) found.set(p.state.slug, p);
  for (const p of plans) {
    if (p.state.stage !== 'closed') continue;
    const scopes = allTasks(p.state).flatMap((t) => t.scope).filter((g) => g !== '**');
    if (scopes.length > 0 && scopesOverlap(globs, scopes)) found.set(p.state.slug, p);
  }
  const top = [...found.values()].sort(byNewest).slice(0, RECALL_PLANS).map((p) => ({ slug: p.state.slug, title: p.state.title, date: p.date, ...(recordRel(p) ?? p.record ? { record: recordRel(p) ?? p.record } : {}) }));
  const uncovered = areas.length ? globs.filter((g) => !areas.some((a) => scopesOverlap([g], a.paths))) : [];
  return { areas, decisions, plans: top, uncovered };
}

const cut = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1)}…` : s);

/** The short index injected at session start. Plans go first when it runs long, then the decision list collapses to ids. '' when there are no areas or decisions (plans alone are not an index). */
export function memoryIndex(root: string, plans: PlanEntry[], maxLines = 60): string {
  const { areas } = loadAreas(root);
  const decisions = loadDecisions(root).filter((d) => d.status === 'active');
  const recent = plans.filter((p) => p.state.stage === 'closed').sort(byNewest).slice(0, 5);
  if (!areas.length && !decisions.length) return '';
  const head = `cairn memory (full picture: ${OVERVIEW_REL}). Before changing code, run \`cairn recall <paths>\`.`;
  const areaLines = areas.length ? ['Areas:', ...areas.map((a) => `- ${a.id}: ${a.summary}`)] : [];
  const decisionLines = decisions.length ? ['Decisions in force:', ...decisions.map((d) => `- ${d.id}: ${cut(d.answer, 100)}`)] : [];
  const planLines = recent.length ? ['Recent plans:', ...recent.map((p) => `- ${p.date} ${p.state.title}`)] : [];
  const build = (d: string[], p: string[]) => [head, ...areaLines, ...d, ...p];
  let out = build(decisionLines, planLines);
  if (out.length > maxLines) out = build(decisionLines, []);
  if (out.length > maxLines && decisions.length) out = build([`Decisions in force: ${decisions.map((d) => d.id).join(', ')}`], []);
  return out.join('\n');
}
