import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { test } from 'node:test';
import { areasForFile, areasForScopes, loadAreas, parseFrontmatter, SYSTEM_DIR } from '../src/areas.ts';
import { pluginRoot } from '../src/util.ts';

const tmp = () => mkdtempSync(join(tmpdir(), 'cairn-areas-'));
const put = (root: string, name: string, text: string) => {
  mkdirSync(join(root, SYSTEM_DIR), { recursive: true });
  writeFileSync(join(root, SYSTEM_DIR, name), text);
};
const APPROVALS = `---
area: Approvals
summary: How approval is proven.
paths: [src/proof.ts, src/approve/**]
updated: 2026-10-27
---

## Rules
`;

test('loads a valid area', () => {
  const root = tmp();
  put(root, 'approvals.md', APPROVALS);
  const { areas, problems } = loadAreas(root);
  assert.deepEqual(problems, []);
  assert.deepEqual(areas[0], {
    id: 'approvals',
    name: 'Approvals',
    summary: 'How approval is proven.',
    paths: ['src/proof.ts', 'src/approve/**'],
    file: 'docs/cairn/system/approvals.md',
  });
});

test('reports bad docs and skips them', () => {
  const cases: [string, string, RegExp][] = [
    ['nofm.md', '# Just text\n', /docs\/cairn\/system\/nofm\.md has no frontmatter/],
    ['nopaths.md', '---\narea: A\nsummary: s\npaths: []\n---\nbody\n', /docs\/cairn\/system\/nopaths\.md needs a non-empty paths list/],
    ['badyaml.md', '---\npaths: [\n---\nbody\n', /docs\/cairn\/system\/badyaml\.md frontmatter is not valid YAML: .+/],
    ['Bad_Name.md', APPROVALS, /docs\/cairn\/system\/Bad_Name\.md file name must be kebab-case/],
    ['noname.md', '---\npaths: [a]\n---\nbody\n', /docs\/cairn\/system\/noname\.md needs area and summary/],
  ];
  for (const [name, text, re] of cases) {
    const root = tmp();
    put(root, name, text);
    const { areas, problems } = loadAreas(root);
    assert.deepEqual(areas, [], name);
    assert.equal(problems.length, 1, name);
    assert.match(problems[0], re, name);
  }
});

test('missing system dir', () => {
  assert.deepEqual(loadAreas(tmp()), { areas: [], problems: [] });
});

test('areas come back sorted by id', () => {
  const root = tmp();
  put(root, 'zeta.md', APPROVALS);
  put(root, 'alpha.md', APPROVALS);
  assert.deepEqual(loadAreas(root).areas.map((a) => a.id), ['alpha', 'zeta']);
});

test('parseFrontmatter splits data and body', () => {
  assert.equal(parseFrontmatter('no fm'), undefined);
  const r = parseFrontmatter('---\na: 1\n---\nbody\n');
  assert.deepEqual(r, { data: { a: 1 }, body: 'body\n' });
});

test('areasForFile and areasForScopes', () => {
  const root = tmp();
  put(root, 'approvals.md', APPROVALS);
  const { areas } = loadAreas(root);
  assert.deepEqual(areasForFile('src/approve/menu.ts', areas).map((a) => a.id), ['approvals']);
  assert.deepEqual(areasForFile('src/other.ts', areas), []);
  assert.deepEqual(areasForScopes(['src/approve/**'], areas).map((a) => a.id), ['approvals']);
  assert.deepEqual(areasForScopes(['src/**'], areas).map((a) => a.id), ['approvals']);
});

test('template has the four sections', () => {
  const md = readFileSync(join(pluginRoot(), 'templates/area.md'), 'utf8');
  const fm = parseFrontmatter(md);
  assert.ok(fm);
  assert.ok('paths' in fm.data);
  const at = ['## Rules', '## How it works', '## Gotchas', '## History'].map((h) => md.indexOf(`\n${h}\n`));
  assert.ok(at.every((i) => i > 0));
  assert.deepEqual([...at].sort((a, b) => a - b), at);
  assert.match(md, /<!-- Generated by cairn from the decision log and plan records\. Edits here are overwritten\. -->/);
});
